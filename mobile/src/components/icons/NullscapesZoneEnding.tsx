const BASE_SIZE = 3.0;

// Real recorded center of the local Gradient-Trigger/Particle cluster in
// this zone (see doc comment, point 2).
const BURST_X = 189.0;
const BURST_Y = 143.8;

// Real Color Trigger values for this zone: starts at this dark navy,
// fades to pure black over 2.000s (matching the trigger's own duration).
const SKY_START = { r: 6, g: 9, b: 12 };
const SKY_END = { r: 0, g: 0, b: 0 };
const FADE_MS = 2000;
const HOLD_MS = 1800;
const RESET_MS = 600;

function depthOpacity(z: number): number {
  return Math.max(0.3, Math.min(1, 0.5 + (z + 3) / 14));
}

function toRgb(t: number): string {
  const r = Math.round(SKY_START.r + (SKY_END.r - SKY_START.r) * t);
  const g = Math.round(SKY_START.g + (SKY_END.g - SKY_START.g) * t);
  const b = Math.round(SKY_START.b + (SKY_END.b - SKY_START.b) * t);
  return `rgb(${r},${g},${b})`;
}

function NullscapesZoneEndingImpl({ style }: { style?: ViewStyle }): React.JSX.Element {
  const reduceMotion = useReducedMotion();
  const fade = useSharedValue(0); // 0 = zone-start navy, 1 = faded to black
  const burstPulse = useSharedValue(0);

  useEffect(() => {
    if (reduceMotion) {
      fade.value = 1;
      burstPulse.value = 0.4;
      return;
    }
    fade.value = withRepeat(
      withSequence(
        withTiming(1, { duration: FADE_MS, easing: Easing.inOut(Easing.sin) }),
        withDelay(HOLD_MS, withTiming(1, { duration: 1 })),
        withTiming(0, { duration: RESET_MS, easing: Easing.out(Easing.quad) }),
      ),
      -1,
      false,
    );
    burstPulse.value = withRepeat(
      withSequence(
        withTiming(1, { duration: 1400, easing: Easing.inOut(Easing.sin) }),
        withTiming(0.25, { duration: 1400, easing: Easing.inOut(Easing.sin) }),
      ),
      -1,
      true,
    );
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [reduceMotion]);

  const skyStyle = useAnimatedStyle(() => ({ backgroundColor: toRgb(fade.value) }));
  const burstStyle = useAnimatedStyle(() => ({
    opacity: burstPulse.value * 0.35,
    transform: [{ scale: 0.8 + burstPulse.value * 0.6 }],
  }));

  const fullBleed = StyleSheet.flatten(style)?.position === 'absolute';

  return (
    <View style={[fullBleed ? styles.fill : styles.wrap, style]} pointerEvents="none" importantForAccessibility="no-hide-descendants">
      <Animated.View style={[styles.sky, skyStyle]} />

      {/* small reprise of the exploding-circle effect at its real recorded
          position — plain View + mixBlendMode, not SVG (an SVG shape with
          `style` crashes on web at runtime; Views are the proven path). */}
      <Animated.View
        style={[
          styles.burstAccent,
          { left: `${(BURST_X / ZONE_VIEW_W) * 100}%`, top: `${(BURST_Y / ZONE_VIEW_H) * 100}%` },
          burstStyle,
        ]}
      />

      <Svg
        style={styles.decorationLayer}
        width="100%"
        height="100%"
        viewBox={`0 0 ${ZONE_VIEW_W} ${ZONE_VIEW_H}`}
        preserveAspectRatio="xMidYMid slice"
      >
        {ZONE_POINTS.map((p, i) => {
          const size = BASE_SIZE * p.s;
          return (
            <Rect
              key={i}
              x={p.x - size / 2}
              y={p.y - size / 2}
              width={size}
              height={size}
              fill={p.c}
              opacity={depthOpacity(p.z)}
              transform={`rotate(${p.rot} ${p.x} ${p.y})`}
            />
          );
        })}
      </Svg>
    </View>
  );
}

export const NullscapesZoneEnding = memo(NullscapesZoneEndingImpl);

const styles = StyleSheet.create({
  wrap: { width: '100%', aspectRatio: ZONE_VIEW_W / ZONE_VIEW_H, borderRadius: 4, overflow: 'hidden' },
  fill: { flex: 1 },
  sky: { ...StyleSheet.absoluteFill },
  // CSS always paints a `position:absolute` element above a `static` one,
  // DOM order notwithstanding — without this, the decoration layer (an
  // otherwise-unpositioned `<Svg>`) silently painted BEHIND `sky` and
  // `burstAccent` (both absolute) despite coming later in JSX. Confirmed
  // via a real browser: all 1,719 `<rect>`s existed in the DOM with
  // correct geometry/fill/opacity and were still invisible until this was
  // added.
  decorationLayer: { ...StyleSheet.absoluteFill },
  burstAccent: {
    position: 'absolute',
    width: 36,
    height: 36,
    marginLeft: -18,
    marginTop: -18,
    borderRadius: 18,
    backgroundColor: '#EAF6FF',
    mixBlendMode: 'screen',
  },
});
