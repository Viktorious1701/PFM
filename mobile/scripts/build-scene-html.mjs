#!/usr/bin/env node
/**
 * Builds src/scene/sceneHtml.generated.ts: the Nullscapes background as one
 * self-contained HTML page, for the Android app's WebView
 * (NullscapesBackground.native.tsx). It carries the same engine the web app
 * draws with (sequenceEngine.ts, transpiled), the Cormorant Garamond face it
 * writes the glitch line in (embedded, so nothing loads from the network),
 * and a small host that keeps the song's clock between syncs from the app.
 *
 *   node scripts/build-scene-html.mjs           # regenerate
 *   node scripts/build-scene-html.mjs --check   # fail if it is out of date
 *
 * Why a WebView: the engine repaints thousands of small shapes per frame,
 * which the phone's browser canvas does at full speed, while every call
 * through React Native's JS→native bridge (react-native-skia) cost too much
 * to keep up — see mobile/AGENTS.md.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const ts = require('typescript');

const ENGINE = join(ROOT, 'src/scene/sequenceEngine.ts');
const FONT = join(ROOT, 'node_modules/@expo-google-fonts/cormorant-garamond/300Light/CormorantGaramond_300Light.ttf');
const OUT = join(ROOT, 'src/scene/sceneHtml.generated.ts');

const engine = ts.transpileModule(readFileSync(ENGINE, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 },
}).outputText;
const font = readFileSync(FONT).toString('base64');

// The host: its own requestAnimationFrame clock, synced by the app.
// __sync({ t, playing, cam, shear, mode }) — t is the song position in ms.
const host = `
(function () {
  var seq = module.exports.createSequence(document.getElementById('c'));
  var post = function (m) { if (window.ReactNativeWebView) window.ReactNativeWebView.postMessage(m); };
  // the clock: t = t0 + (now - at) while playing; small drifts are eased out
  var s = { t0: 0, at: 0, playing: false, cam: 0, shear: 0, mode: 'full', fix: 0, fixAt: 0, ready: false };
  var EASE_MS = 250, SNAP_MS = 60;
  function clock(now) {
    var base = s.playing ? s.t0 + (now - s.at) : s.t0;
    var k = Math.min(1, (now - s.fixAt) / EASE_MS);
    return base + s.fix * k;
  }
  window.__sync = function (m) {
    var now = performance.now();
    var shown = clock(now);
    if (m.mode !== s.mode) { s.mode = m.mode; seq.setMode(m.mode); }
    s.cam = m.cam; s.shear = m.shear;
    var drift = m.t - shown;
    if (!m.playing || !s.playing || Math.abs(drift) > SNAP_MS) {
      s.t0 = m.t; s.fix = 0;
    } else {
      s.t0 = shown; s.fix = drift; s.fixAt = now;
    }
    s.at = now; s.playing = m.playing; s.ready = true;
  };
  var last = '', frames = 0, spent = 0, windowAt = performance.now();
  function frame(now) {
    if (s.ready) {
      var t = clock(now);
      var key = s.mode + '|' + Math.round(t) + '|' + s.cam.toFixed(1) + '|' + s.shear.toFixed(4);
      if (key !== last) {
        last = key;
        var a = performance.now();
        seq.render(t, s.cam, s.shear);
        spent += performance.now() - a; frames++;
      }
    }
    if (now - windowAt >= 2000) {
      if (frames) post(JSON.stringify({ fps: +(frames * 1000 / (now - windowAt)).toFixed(1), avgMs: +(spent / frames).toFixed(1) }));
      frames = 0; spent = 0; windowAt = now;
    }
    requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);
  document.fonts.load('64px "CormorantGaramond_300Light"').then(function () { post('ready'); }, function () { post('ready'); });
})();`;

const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>
@font-face { font-family: "CormorantGaramond_300Light"; src: url(data:font/ttf;base64,${font}) format("truetype"); }
html, body { margin: 0; height: 100%; overflow: hidden; background: #0f1d33; }
canvas { position: fixed; inset: 0; width: 100%; height: 100%; object-fit: cover; display: block; }
</style></head>
<body><canvas id="c" width="1280" height="720"></canvas>
<script>var module = { exports: {} }, exports = module.exports;</script>
<script>${engine}</script>
<script>${host}</script>
</body></html>`;

const out = `// GENERATED by scripts/build-scene-html.mjs from src/scene/sequenceEngine.ts — do not edit.
// Regenerate with \`npm run scene:html\`; \`npm run typecheck\` fails while it is stale.
/* eslint-disable */
export const SCENE_HTML: string = ${JSON.stringify(html)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {}
  if (current !== out) {
    console.error('src/scene/sceneHtml.generated.ts is out of date with sequenceEngine.ts — run `npm run scene:html`.');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${Math.round(out.length / 1024)} KB)`);
}
